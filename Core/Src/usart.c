/**
 * @brief 串口空闲中断回调函数
 * @param huart 串口句柄
 * @param Size 接收数据长度
 */
void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef *huart, uint16_t Size) {
  if (huart->Instance == USART1) {
    if (huart->RxEventType == HAL_UART_RXEVENT_IDLE) {
      extern osMessageQueueId_t Usart1_Rx_DataHandle;

      // 发送接收数据到消息队列
      osStatus_t state;
      for (uint16_t i = 0; i < Size; i++) {
        state = osMessageQueuePut(Usart1_Rx_DataHandle, &rxBuffer[i], NULL, 0);
        if (state != osOK) {
          logWarning("Failed to put data into message queue, code: %d", state);
          break; // 如果队列满了，跳出循环
        }
      }

    }
    // 重新开启空闲中断接收
    HAL_UARTEx_ReceiveToIdle_IT(&huart1, rxBuffer, USART1_RX_BUF_SIZE);
  }
}

